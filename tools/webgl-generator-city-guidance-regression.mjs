import assert from "node:assert/strict";
import {CityUpdateGuidance} from "../app/webgl-generator/src/runtime/city-update-guidance.js";
let identity = "a";
const map = {};
const guidance = new CityUpdateGuidance({getIdentity: () => identity, getMap: () => map});
assert.equal(guidance.read(0).known, false);
const attribute = {cityUpdateGuidance: {cityId: 0, attribute: "walls", reason: "设置城墙"}};
guidance.mutation({action: "execute", command: attribute});
assert.deepEqual(guidance.read(0).domains.map(item => item.id), ["population", "economy", "military"]);
const rebuild = {effects: {affected: [{kind: "derived-system", id: "economy-rebuild"}]}};
guidance.mutation({action: "execute", command: rebuild});
assert.deepEqual(guidance.read(0).domains.map(item => item.id), ["population", "military"]);
guidance.mutation({action: "undo", command: rebuild});
assert.equal(guidance.read(0).domains.some(item => item.id === "economy"), true);
guidance.mutation({action: "undo", command: attribute});
assert.equal(guidance.read(0).known, false);
guidance.mutation({action: "redo", command: attribute});
map.regenerationLocks = {entries: [{kind: "state", id: 1}]};
guidance.mutation({action: "execute", command: {effects: rebuild.effects}});
assert.equal(guidance.read(0).domains.some(item => item.id === "economy"), true);
identity = "b";
assert.equal(guidance.read(0).known, false);
console.log(JSON.stringify({ok: true, cases: 7}));
