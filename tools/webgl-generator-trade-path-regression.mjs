import assert from "node:assert/strict";
import {diagnoseTradePath} from "../app/webgl-generator/src/runtime/trade-path-diagnostics.js";
const map = {pack: {cells: {p: [[0,0],[3,0],[3,4],[9,9]], h: [30,30,30,30], c: [[1],[0,2],[1],[]]}, burgs: [null,{cell:0},{cell:2}], markets: [{i:0,centerBurgId:1}], deals: [{i:0,sellerType:"market",seller:0,buyerType:"burg",buyer:2}]}, settlements:{routes:[{id:0,type:"road",packCells:[0,1]},{id:1,type:"trail",packCells:[1,2]},{id:2,type:"road",packCells:[0,1]}]}};
const before = JSON.stringify(map);
assert.equal((await diagnoseTradePath(map, 0)).length, 7);
assert.equal(JSON.stringify(map), before);
map.settlements.routes.splice(1,1);
assert.equal((await diagnoseTradePath(map, 0)).status, "unreachable");
map.settlements.routes.push({id:3,packCells:[0,2]});
assert.equal((await diagnoseTradePath(map, 0)).status, "unknown");
map.pack.markets[0].centerBurgId = 999;
assert.equal((await diagnoseTradePath(map, 0)).status, "unknown");
const sea = {pack:{cells:{p:[[0,0],[1,0],[2,0],[3,0]],h:[30,10,10,30],c:[[1],[0,2],[1,3],[2]],haven:[1,0,0,2],f:[0,1,1,0],t:[1,-1,-1,1],temp:[10,10,10,10]},features:[null,{type:'ocean',land:false}],burgs:[{cell:0,port:1},{cell:3,port:1}],deals:[{i:0,sellerType:'burg',seller:0,buyerType:'burg',buyer:1}]},settlements:{routes:[{id:0,type:'searoute',packCells:[0,1,2,3]}]}};
assert.equal((await diagnoseTradePath(sea,0)).length,3,'合法港口沿实际海路换乘');
sea.pack.burgs[1].port=2;
assert.equal((await diagnoseTradePath(sea,0)).status,'unreachable','视觉抵达不替代有效港口');
sea.pack.burgs[1].port=1;
sea.pack.cells.haven[3]=1;
assert.equal((await diagnoseTradePath(sea,0)).status,'unknown','损坏海路资料不能冒充确定断路');
assert.deepEqual(await diagnoseTradePath(map,0,()=>false),{status:'unknown',message:'交易两端的城市或市场中心缺失，无法判断。'});
console.log("交易路径：市场中心、支路、共享边、长度、断路、损坏、只读及港口换乘通过");
