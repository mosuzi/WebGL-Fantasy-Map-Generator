import assert from "node:assert/strict";
import {MapSaveState} from "../app/webgl-generator/src/runtime/map-save-state.js";

let identity = "map-a";
let presentation = {units: "km", theme: "default"};
const state = new MapSaveState({getIdentity: () => identity, getPresentation: () => presentation});
assert.equal(state.getStatus().dirty, true);
const original = state.capture();
state.record(original, "browser");
assert.equal(state.getStatus().dirty, false);
const command = {};
state.mutation({action: "execute", command});
assert.equal(state.getStatus().dirty, true);
state.record(original, "cloud");
assert.equal(state.getStatus().dirty, true, "迟到保存不能覆盖新修改状态");
state.mutation({action: "undo", command});
assert.equal(state.getStatus().dirty, false, "撤销回保存内容必须恢复已保存状态");
state.mutation({action: "redo", command});
assert.equal(state.getStatus().dirty, true);
state.record(state.capture(), "download", "example.webfmg");
assert.equal(state.getStatus().dirty, false);
presentation = {...presentation, units: "mi"};
assert.equal(state.getStatus().dirty, true, "随档单位更改需要保存");
presentation = {...presentation, units: "km"};
assert.equal(state.getStatus().dirty, false);
const oldTicket = state.capture();
const newTicket = state.capture();
state.record(newTicket, "cloud", "new");
assert.equal(state.record(oldTicket, "cloud", "old"), false, "旧回执不得覆盖较新的同目的地保存");
const snapshot = state.snapshot();
identity = "map-b";
assert.equal(state.getStatus().dirty, true);
assert.equal(state.record(newTicket, "browser"), false, "跨图回执必须拒绝");
identity = "map-a";
state.restorePosition(snapshot);
assert.equal(state.getStatus().dirty, false, "失败恢复必须保持原保存凭据");
console.log(JSON.stringify({ok: true, cases: 12}));
